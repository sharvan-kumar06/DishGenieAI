import json
import re
from typing import Any, Dict, List, Optional
from app.schemas.recipe import Recipe, Substitution


def parse_recipe_text(
    raw_text: str,
    fallback_ingredients: Optional[List[str]] = None,
    cuisine: Optional[str] = None,
    diet: Optional[str] = None,
    additional_ingredients: Optional[str] = None,
    candidate_recipe: Optional[Dict[str, Any]] = None,
) -> Optional[Recipe]:
    """
    Parses raw text generated by Qwen2.5 into a structured Recipe schema.
    Handles:
      - Markdown headers (### Name, ## Ingredients, etc.)
      - Standard plain text headers (NAME:, INGREDIENTS:, etc.)
      - JSON fenced code blocks (```json ... ```)
      - Direct bulleted and numbered instruction lists
    Falls back gracefully with reference recipe information if parsing is partial.
    """
    if not raw_text or not raw_text.strip():
        # Fallback using candidate recipe if available
        if candidate_recipe:
            return create_recipe_from_candidate(candidate_recipe, fallback_ingredients, diet)
        return None

    text = raw_text.strip()

    # 1. Attempt JSON parsing if text contains JSON
    json_match = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", text, re.DOTALL)
    if not json_match:
        json_match = re.search(r"(\{[\s\S]*\"name\"[\s\S]*\"ingredients\"[\s\S]*\})", text)

    if json_match:
        try:
            data = json.loads(json_match.group(1))
            name = data.get("name") or data.get("recipe_name") or "Chef's Special"
            desc = data.get("description") or "A delicious handcrafted meal."
            ings = data.get("ingredients") or []
            insts = data.get("instructions") or []
            subs = []
            for s in data.get("substitutions", []):
                if isinstance(s, dict):
                    subs.append(Substitution(ingredient=s.get("ingredient", "Item"), replacement=s.get("replacement", "Substitute")))
                elif isinstance(s, str) and ":" in s:
                    p1, p2 = s.split(":", 1)
                    subs.append(Substitution(ingredient=p1.strip(), replacement=p2.strip()))
            shops = data.get("shopping_list") or []
            if ings and insts:
                return Recipe(
                    name=name,
                    description=desc,
                    ingredients=[str(i) for i in ings],
                    instructions=[str(i) for i in insts],
                    substitutions=subs or default_substitutions(fallback_ingredients),
                    shopping_list=[str(s) for s in shops] or ["Cooking oil", "Salt & spices"],
                )
        except Exception:
            pass

    # 2. Section markers supporting markdown headers, bold headers, and plain text
    section_patterns = {
        "name": r"(?:#{1,4}\s*)?(?:\*{0,2})(?:RECIPE\s+NAME|NAME|TITLE)(?:\*{0,2}):?\s*(.*?)(?=(?:#{1,4}\s*)?(?:\*{0,2})(?:DESCRIPTION|INGREDIENTS|INSTRUCTIONS|SUBSTITUTIONS|SHOPPING|$))",
        "description": r"(?:#{1,4}\s*)?(?:\*{0,2})(?:DESCRIPTION|ABOUT|SUMMARY)(?:\*{0,2}):?\s*(.*?)(?=(?:#{1,4}\s*)?(?:\*{0,2})(?:INGREDIENTS|INSTRUCTIONS|SUBSTITUTIONS|SHOPPING|$))",
        "ingredients": r"(?:#{1,4}\s*)?(?:\*{0,2})(?:INGREDIENTS|INGREDIENT\s+LIST)(?:\*{0,2}):?\s*(.*?)(?=(?:#{1,4}\s*)?(?:\*{0,2})(?:INSTRUCTIONS|DIRECTIONS|STEPS|METHOD|SUBSTITUTIONS|SHOPPING|$))",
        "instructions": r"(?:#{1,4}\s*)?(?:\*{0,2})(?:INSTRUCTIONS|DIRECTIONS|STEPS|METHOD|PREPARATION)(?:\*{0,2}):?\s*(.*?)(?=(?:#{1,4}\s*)?(?:\*{0,2})(?:SUBSTITUTIONS|SUBSTITUTES|SHOPPING\s+LIST|SHOPPING|$))",
        "substitutions": r"(?:#{1,4}\s*)?(?:\*{0,2})(?:SUBSTITUTIONS|SUBSTITUTES)(?:\*{0,2}):?\s*(.*?)(?=(?:#{1,4}\s*)?(?:\*{0,2})(?:SHOPPING\s+LIST|SHOPPING|$))",
        "shopping_list": r"(?:#{1,4}\s*)?(?:\*{0,2})(?:SHOPPING\s+LIST|SHOPPING)(?:\*{0,2}):?\s*(.*?)(?=$)",
    }

    extracted: Dict[str, str] = {}
    for key, pattern in section_patterns.items():
        match = re.search(pattern, text, re.IGNORECASE | re.DOTALL)
        if match:
            extracted[key] = match.group(1).strip()

    # Parse Name
    recipe_name = extracted.get("name", "").strip()
    if not recipe_name:
        for line in text.split("\n"):
            line = line.strip().strip("#* ")
            if line and len(line) < 70 and not any(kw in line.lower() for kw in ["ingredient", "instruction", "step", "diet", "when you", "here is"]):
                recipe_name = re.sub(r"^(?:RECIPE(?:\s+NAME)?:\s*)", "", line, flags=re.IGNORECASE).strip()
                break

    if not recipe_name:
        if candidate_recipe and candidate_recipe.get("name"):
            recipe_name = candidate_recipe["name"]
        else:
            ing_names = ", ".join(fallback_ingredients[:2]) if fallback_ingredients else "Fresh Vegetable"
            cuisine_prefix = f"{cuisine} " if cuisine and cuisine.lower() != "any cuisine" else ""
            recipe_name = f"{cuisine_prefix}{ing_names} Special"

    # Parse Description
    description = extracted.get("description", "").strip()
    if not description:
        diet_str = f" {diet.lower()}" if diet and diet.lower() != "no preference" else ""
        description = f"A flavorful{diet_str} culinary creation combining fresh ingredients and aromatic seasonings."

    # Parse Ingredients
    ingredients_raw = extracted.get("ingredients", "")
    ingredients: List[str] = []
    if ingredients_raw:
        for line in ingredients_raw.split("\n"):
            cleaned = re.sub(r"^[\s*•\-–—\d\.\)]+", "", line).strip()
            if cleaned and len(cleaned) > 1 and not cleaned.lower().startswith(("ingredient", "instruction", "step")):
                ingredients.append(cleaned)

    if not ingredients:
        if candidate_recipe and candidate_recipe.get("ingredients_raw"):
            raw_parts = [p.strip() for p in candidate_recipe["ingredients_raw"].split(",") if p.strip()]
            ingredients.extend(raw_parts[:10])
        elif fallback_ingredients:
            ingredients.extend(fallback_ingredients)
            if additional_ingredients:
                extras = [i.strip() for i in additional_ingredients.split(",") if i.strip()]
                ingredients.extend(extras)

    # Parse Instructions
    instructions_raw = extracted.get("instructions", "")
    instructions: List[str] = []
    if instructions_raw:
        for line in instructions_raw.split("\n"):
            cleaned = re.sub(r"^[\s*•\-–—\d\.\)]+", "", line).strip()
            if cleaned and len(cleaned) > 5 and not cleaned.lower().startswith(("substitut", "shopping")):
                instructions.append(cleaned)

    if not instructions:
        # Split sentences from text or fallback candidate
        if candidate_recipe and candidate_recipe.get("instructions"):
            steps = [s.strip() for s in candidate_recipe["instructions"].split("\n") if len(s.strip()) > 8]
            instructions.extend(steps)
        else:
            sentences = [
                s.strip()
                for s in re.split(r"(?<=[.!?])\s+", text)
                if len(s.strip()) > 10 and not any(h in s.lower() for h in ["recipe name:", "cuisine:", "diet:"])
            ]
            instructions.extend(sentences)

    # Parse Substitutions
    substitutions: List[Substitution] = []
    subs_raw = extracted.get("substitutions", "")
    if subs_raw:
        for line in subs_raw.split("\n"):
            line = re.sub(r"^[\s*•\-–—]+", "", line).strip()
            if not line:
                continue
            if ":" in line:
                parts = line.split(":", 1)
                substitutions.append(Substitution(ingredient=parts[0].strip(), replacement=parts[1].strip()))
            elif "->" in line:
                parts = line.split("->", 1)
                substitutions.append(Substitution(ingredient=parts[0].strip(), replacement=parts[1].strip()))

    if not substitutions:
        substitutions = default_substitutions(fallback_ingredients)

    # Parse Shopping List
    shopping_list: List[str] = []
    shop_raw = extracted.get("shopping_list", "")
    if shop_raw:
        for line in shop_raw.split("\n"):
            line = re.sub(r"^[\s*•\-–—\d\.\)]+", "", line).strip()
            if line and len(line) > 1:
                shopping_list.append(line)

    if not shopping_list:
        shopping_list = [
            "Cold-pressed oil or ghee",
            "Aromatic spices (cumin, coriander, turmeric)",
            "Fresh herbs (cilantro, curry leaves)",
        ]

    if not instructions or not ingredients:
        if candidate_recipe:
            return create_recipe_from_candidate(candidate_recipe, fallback_ingredients, diet)
        return None

    return Recipe(
        name=recipe_name,
        description=description,
        ingredients=ingredients,
        instructions=instructions,
        substitutions=substitutions,
        shopping_list=shopping_list,
    )


def default_substitutions(fallback_ingredients: Optional[List[str]] = None) -> List[Substitution]:
    """Generates standard pantry substitutions."""
    primary = fallback_ingredients[0] if fallback_ingredients else "Primary vegetable"
    return [
        Substitution(
            ingredient=primary,
            replacement="Can be substituted with seasonal squash, bell pepper, or potatoes.",
        ),
        Substitution(
            ingredient="Cooking oil",
            replacement="Can use ghee, coconut oil, or butter based on dietary preference.",
        ),
    ]


def create_recipe_from_candidate(
    candidate: Dict[str, Any],
    confirmed_ingredients: Optional[List[str]] = None,
    diet: Optional[str] = None,
) -> Recipe:
    """Builds a structured Recipe schema directly from a candidate database row."""
    name = candidate.get("name", "Gourmet Kitchen Recipe")
    raw_ings = candidate.get("ingredients_raw", "")
    ings_list = [p.strip() for p in raw_ings.split(",") if p.strip()] if raw_ings else (confirmed_ingredients or [])
    
    raw_insts = candidate.get("instructions", "")
    insts_list = [s.strip() for s in raw_insts.split("\n") if len(s.strip()) > 8]
    if not insts_list:
        insts_list = [
            f"Prepare and wash fresh {', '.join(confirmed_ingredients or ['ingredients'])} thoroughly.",
            "Heat oil or seasoning in a pan and saute aromatics until fragrant.",
            "Add main vegetables and spices, simmering until tender and fully cooked.",
            "Garnish with fresh herbs and serve warm.",
        ]

    diet_str = f" {diet.lower()}" if diet and diet.lower() != "no preference" else ""
    return Recipe(
        name=name,
        description=f"Authentic {candidate.get('cuisine', 'Indian')} recipe naturally balanced for a{diet_str} diet.",
        ingredients=ings_list,
        instructions=insts_list,
        substitutions=default_substitutions(confirmed_ingredients),
        shopping_list=[
            "Pantry spices (turmeric, cumin seeds, coriander powder)",
            "Cooking oil or ghee",
            "Salt to taste",
        ],
    )
