import re
from typing import Dict, List, Optional
from app.schemas.recipe import Recipe, Substitution


def parse_recipe_text(
    raw_text: str,
    fallback_ingredients: Optional[List[str]] = None,
    cuisine: Optional[str] = None,
    diet: Optional[str] = None,
    additional_ingredients: Optional[str] = None,
) -> Optional[Recipe]:
    """
    Parses raw text generated by FLAN-T5 into a structured Recipe schema.
    Attempts to identify:
      - RECIPE NAME
      - DESCRIPTION
      - INGREDIENTS
      - INSTRUCTIONS
      - SUBSTITUTIONS
      - SHOPPING LIST

    If structured section headers are present, parses them directly.
    If the model outputs narrative cooking text, converts it into structured steps.
    If parsing fails completely, returns None so raw_text can be served.
    """
    if not raw_text or not raw_text.strip():
        return None

    text = raw_text.strip()

    # Section markers to look for
    section_patterns = {
        "name": r"(?:RECIPE\s+NAME|NAME|TITLE):\s*(.*?)(?=(?:DESCRIPTION|INGREDIENTS|INSTRUCTIONS|SUBSTITUTIONS|SHOPPING|$))",
        "description": r"(?:DESCRIPTION|ABOUT):\s*(.*?)(?=(?:INGREDIENTS|INSTRUCTIONS|SUBSTITUTIONS|SHOPPING|$))",
        "ingredients": r"(?:INGREDIENTS|INGREDIENT\s+LIST):\s*(.*?)(?=(?:INSTRUCTIONS|DIRECTIONS|STEPS|SUBSTITUTIONS|SHOPPING|$))",
        "instructions": r"(?:INSTRUCTIONS|DIRECTIONS|STEPS|METHOD):\s*(.*?)(?=(?:SUBSTITUTIONS|SUBSTITUTES|SHOPPING\s+LIST|SHOPPING|$))",
        "substitutions": r"(?:SUBSTITUTIONS|SUBSTITUTES):\s*(.*?)(?=(?:SHOPPING\s+LIST|SHOPPING|$))",
        "shopping_list": r"(?:SHOPPING\s+LIST|SHOPPING):\s*(.*?)(?=$)",
    }

    extracted: Dict[str, str] = {}
    has_explicit_headers = False
    for key, pattern in section_patterns.items():
        match = re.search(pattern, text, re.IGNORECASE | re.DOTALL)
        if match:
            extracted[key] = match.group(1).strip()
            has_explicit_headers = True

    # 1. Parse Name
    recipe_name = extracted.get("name", "").strip()
    if not recipe_name:
        first_line = text.split("\n")[0].strip()
        if len(first_line) < 70 and not any(kw in first_line.lower() for kw in ["ingredient", "instruction", "step", "diet", "when you"]):
            recipe_name = re.sub(r"^(?:RECIPE(?:\s+NAME)?:\s*)", "", first_line, flags=re.IGNORECASE).strip()
    if not recipe_name:
        ingredients_str = ", ".join(fallback_ingredients[:2]) if fallback_ingredients else "Fresh Vegetable"
        cuisine_prefix = f"{cuisine} " if cuisine and cuisine.lower() != "any cuisine" else ""
        recipe_name = f"{cuisine_prefix}{ingredients_str} Delight"

    # 2. Parse Description
    description = extracted.get("description", "").strip()
    if not description:
        diet_str = f" {diet.lower()}" if diet and diet.lower() != "no preference" else ""
        description = f"A flavorful{diet_str} dish crafted with locally detected ingredients and aromatic spices."

    # 3. Parse Ingredients
    ingredients_raw = extracted.get("ingredients", "")
    ingredients: List[str] = []
    if ingredients_raw:
        for line in ingredients_raw.split("\n"):
            line = re.sub(r"^[\s*•\-–—\d\.\)]+", "", line).strip()
            if line and len(line) > 1 and not line.lower().startswith(("ingredients", "instructions")):
                ingredients.append(line)

    # If no explicit ingredients parsed, combine confirmed + additional
    if not ingredients:
        if fallback_ingredients:
            ingredients.extend(fallback_ingredients)
        if additional_ingredients:
            extras = [item.strip() for item in additional_ingredients.split(",") if item.strip()]
            ingredients.extend(extras)

    # 4. Parse Instructions
    instructions_raw = extracted.get("instructions", "")
    instructions: List[str] = []
    if instructions_raw:
        for line in instructions_raw.split("\n"):
            cleaned = re.sub(r"^[\s*•\-–—\d\.\)]+", "", line).strip()
            if cleaned and len(cleaned) > 3 and not cleaned.lower().startswith(("substitutions", "shopping")):
                instructions.append(cleaned)

    # If instructions were not under an explicit header, extract sentences from text
    if not instructions:
        # Split text into logical sentences
        sentences = [
            s.strip()
            for s in re.split(r"(?<=[.!?])\s+", text)
            if len(s.strip()) > 10 and not any(h in s.lower() for h in ["recipe name:", "cuisine:", "diet:"])
        ]
        if sentences:
            instructions = sentences

    # 5. Parse Substitutions
    substitutions: List[Substitution] = []
    subs_raw = extracted.get("substitutions", "")
    if subs_raw:
        for line in subs_raw.split("\n"):
            line = re.sub(r"^[\s*•\-–—]+", "", line).strip()
            if not line:
                continue
            if ":" in line:
                parts = line.split(":", 1)
                substitutions.append(Substitution(ingredient=parts[0].strip(), replacement=parts[1].strip()))
            elif "->" in line:
                parts = line.split("->", 1)
                substitutions.append(Substitution(ingredient=parts[0].strip(), replacement=parts[1].strip()))
            elif len(line) > 3:
                substitutions.append(Substitution(ingredient="Alternative", replacement=line))

    # Add smart default substitution if none generated
    if not substitutions and fallback_ingredients:
        primary_item = fallback_ingredients[0]
        substitutions.append(
            Substitution(
                ingredient=primary_item,
                replacement=f"Can be substituted with seasonal squash, bell pepper, or zucchini if unavailable.",
            )
        )

    # 6. Parse Shopping List
    shopping_list: List[str] = []
    shop_raw = extracted.get("shopping_list", "")
    if shop_raw:
        for line in shop_raw.split("\n"):
            line = re.sub(r"^[\s*•\-–—\d\.\)]+", "", line).strip()
            if line and len(line) > 1:
                shopping_list.append(line)

    if not shopping_list:
        shopping_list = ["Olive oil or cooking butter", "Salt & freshly ground black pepper", "Aromatic herbs / spices"]

    # Final validation
    if not instructions or not ingredients:
        return None

    return Recipe(
        name=recipe_name,
        description=description,
        ingredients=ingredients,
        instructions=instructions,
        substitutions=substitutions,
        shopping_list=shopping_list,
    )
